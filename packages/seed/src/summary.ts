import { formatWindow, indexSeason, type SeasonData } from '@bvac/core';

/** Markdown overview of a season bundle: counts per division, teams and slots. */
export function summarizeSeason(data: SeasonData): string {
  const index = indexSeason(data);
  const lines: string[] = [];
  lines.push(`# ${data.season.name} — sample data`);
  lines.push('');
  lines.push('Fictional season generated by `pnpm seed`. Every person, team and registration is made up.');
  lines.push('');
  lines.push(
    `${data.players.length} players in ${data.households.length} households · ${data.registrations.length} registrations · ` +
      `${data.teams.length} team options · ${data.coachAssignments.length} coaches · ${data.practiceSlots.length} practice slots · ${data.gameSlots.length} game slots`,
  );
  lines.push('');
  lines.push('| Division | Grades | Registrations (early / regular / late) | Teams | Seats at preferred / max | Size min / pref / max | Model |');
  lines.push('| --- | --- | --- | --- | --- | --- | --- |');
  for (const d of data.divisions) {
    const regs = index.registrationsByDivision.get(d.id) ?? [];
    const teams = index.teamsByDivision.get(d.id) ?? [];
    const w = (x: string) => regs.filter((r) => r.window === x).length;
    const { min, preferred, max } = d.settings.teamSize;
    lines.push(
      `| ${d.name} (${d.code}) | ${d.label} | ${regs.length} (${w('early')} / ${w('regular')} / ${w('late')}) | ${teams.length} | ` +
        `${teams.length * preferred} / ${teams.length * max} | ${min} / ${preferred} / ${max} | ${d.settings.model} |`,
    );
  }
  lines.push('');
  lines.push('## Team options');
  lines.push('');
  lines.push('| Division | Option | Practice | Field | Head coach | 1st-choice requests |');
  lines.push('| --- | --- | --- | --- | --- | --- |');
  for (const t of data.teams) {
    const slot = index.practiceSlot.get(t.practiceSlotId)!;
    const coach = index.coachesByTeam.get(t.id)?.find((c) => c.role === 'head');
    const person = coach ? index.person.get(coach.personId) : undefined;
    const firsts = data.registrations.filter((r) => r.choices.some((c) => c.teamId === t.id && c.rank === 1)).length;
    lines.push(
      `| ${index.division.get(t.divisionId)!.code} | ${t.label} | ${formatWindow(slot.window)} | ${index.field.get(slot.fieldId)!.name} | ` +
        `${person ? `${person.firstName} ${person.lastName}` : '—'} | ${firsts} |`,
    );
  }
  const requests = data.registrations.flatMap((r) => r.requests);
  const by = (s: string) => requests.filter((q) => q.matchStatus === s).length;
  lines.push('');
  lines.push(
    `Player requests: ${requests.length} (${requests.filter((q) => q.type === 'sibling').length} sibling, ` +
      `${requests.filter((q) => q.type === 'friend').length} friend) · matched ${by('matched')} · ambiguous ${by('ambiguous')} · unmatched ${by('unmatched')}`,
  );
  lines.push(
    `Coach requests: ${data.registrations.filter((r) => r.coachRequest).length} · ` +
      `players with history: ${new Set(data.playerHistory.map((h) => h.playerId)).size} · ` +
      `required-days families: ${data.registrations.filter((r) => r.availabilityRequired).length}`,
  );
  lines.push('');
  return lines.join('\n');
}
